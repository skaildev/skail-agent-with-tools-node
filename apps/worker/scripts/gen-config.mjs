// The function cannot read environment variables, so the settings the provider needs are written into
// src/build-config.generated.ts (git-ignored) at build time, from the environment or .env.
// The planner settings (OPENAI_API_KEY, OPENAI_MODEL, SAMPLE_PLANNER_DELAY_MS) are not here: the commands read them
// from process.env when they run.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadEnv } from "./env.mjs";

const env = loadEnv();
const config = {
  webBaseUrl: env.WEB_BASE_URL || "http://localhost:8080",
};
const file = fileURLToPath(new URL("../src/build-config.generated.ts", import.meta.url));
writeFileSync(
  file,
  `// generated by scripts/gen-config.mjs; do not edit\nexport const buildConfig = ${JSON.stringify(config, null, 2)};\n`,
);
console.log(`worker config: web=${config.webBaseUrl}`);
